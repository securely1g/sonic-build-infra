"""Add declared service accounts without replacing the base image's accounts."""

import argparse
import hashlib
import json
from pathlib import Path
import re

from sonic_oci.files import read_files
from sonic_oci.layout import validate_layout


def require(value, message):
    if not value:
        raise ValueError(message)


def records(contents, kind):
    rows, numbers = {}, {}
    for line in contents.decode("utf-8").splitlines():
        if not line:
            continue
        fields = line.split(":")
        require(len(fields) == (7 if kind == "passwd" else 4), "invalid " + kind + " record")
        name = fields[0]
        require(re.fullmatch(r"[a-z_][a-z0-9_-]*\$?", name), "invalid account name: " + name)
        require(name not in rows and "\x00" not in line, "duplicate or invalid account: " + name)
        indexes = (2, 3) if kind == "passwd" else (2,)
        require(all(fields[i].isdigit() and int(fields[i]) < 2**32 - 1 for i in indexes), "invalid account ID: " + name)
        rows[name] = fields
        numbers.setdefault(int(fields[2]), set()).add(name)
    return rows, numbers


def merge(original, additions, kind):
    existing, numbers = records(original, kind)
    requested, _ = records(additions, kind)
    lines = []
    for name, fields in requested.items():
        if name in existing:
            require(existing[name] == fields, "account differs from the base: " + name)
            continue
        number = int(fields[2])
        require(number not in numbers, "account ID already belongs to " + ",".join(sorted(numbers.get(number, []))))
        numbers[number] = {name}
        existing[name] = fields
        lines.append(":".join(fields))
    if not lines:
        return original
    return original + (b"\n" if original and not original.endswith(b"\n") else b"") + ("\n".join(lines) + "\n").encode()


def build(base, users, groups, architecture):
    layout = validate_layout(base, "linux/" + architecture)
    names = {"etc/passwd", "etc/group"}
    original = read_files(layout.layers, names)
    require(set(original) == names, "base image lacks passwd or group")
    additions = read_files([users, groups], names)
    require(set(additions) == names, "account additions lack passwd or group")
    merged = {}
    for path in sorted(names):
        contents, member = original[path]
        require(member.uid == member.gid == 0 and member.mode == 0o644, "unsupported base account file ownership or mode: " + path)
        merged[path] = merge(contents, additions[path][0], path.split("/")[-1])
    passwd, _ = records(merged["etc/passwd"], "passwd")
    group, _ = records(merged["etc/group"], "group")
    gids = {int(row[2]) for row in group.values()}
    requested, _ = records(additions["etc/passwd"][0], "passwd")
    require(all(int(row[3]) in gids for row in requested.values()), "service account primary group is absent")
    requested_groups, _ = records(additions["etc/group"][0], "group")
    require(all(not row[3] or set(row[3].split(",")) <= set(passwd) for row in requested_groups.values()),
            "service group contains an absent user")
    receipt = {
        "_generated": "AUTO-GENERATED by sonic-build-infra/oci/accounts.py. DO NOT EDIT MANUALLY.",
        "schema": 1, "architecture": architecture, "base_manifest_digest": layout.descriptor["digest"],
        "users": list(requested), "groups": list(requested_groups),
        "files": {path: {"base_sha256": hashlib.sha256(original[path][0]).hexdigest(),
                         "sha256": hashlib.sha256(contents).hexdigest(), "uid": 0, "gid": 0, "mode": 0o644}
                  for path, contents in merged.items()},
    }
    return merged, receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("base", "users", "groups", "passwd-out", "group-out", "receipt"):
        parser.add_argument("--" + name, required=True, type=Path)
    parser.add_argument("--architecture", required=True, choices=("amd64", "arm64"))
    args = parser.parse_args()
    files, receipt = build(args.base, args.users, args.groups, args.architecture)
    args.passwd_out.write_bytes(files["etc/passwd"])
    args.group_out.write_bytes(files["etc/group"])
    args.receipt.write_text(json.dumps(receipt, sort_keys=True, indent=2) + "\n")


if __name__ == "__main__":
    main()
