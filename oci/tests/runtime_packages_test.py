"""Protect Debian metadata ownership and target-library isolation.

The public-rule test exercises real dpkg ELF analysis. These tests cover the
failure boundaries that must be checked before those tools receive inputs.
"""

import io
import json
from pathlib import Path
import struct
import tarfile
import tempfile
import unittest
from unittest.mock import patch

from runtime_packages import (
    DebianTools, check_substitutions, dependency_records, elf_files, merge,
    read_substvars, sha, source_definition, tool_environment,
    unique_dependencies, validate_archive, validate_required_paths,
)


class RuntimePackagesTest(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.control = self.root / "control"
        self.changelog = self.root / "changelog"
        self.control.write_text(
            "Source: example\nMaintainer: Example <example@example.invalid>\n"
            "Section: libs\nPriority: optional\n\n"
            "Package: libexample\nArchitecture: any\n"
            "Depends: ${shlibs:Depends}, ${misc:Pre-Depends}\n"
            "Description: Original description\n")
        self.changelog.write_text(
            "example (1.2.3-1) unstable; urgency=medium\n\n  * Example.\n\n"
            " -- Example <example@example.invalid>  Thu, 01 Jan 1970 00:00:00 +0000\n")

    def test_control_and_changelog_remain_the_only_package_facts(self):
        """Editing existing Debian metadata changes the generated inputs directly."""
        source, packages, version = source_definition(self.control, self.changelog)
        self.assertEqual(source["Maintainer"], "Example <example@example.invalid>")
        self.assertEqual(version, "1.2.3-1")
        self.assertEqual(packages["libexample"]["Description"], "Original description")
        self.control.write_text(self.control.read_text().replace("Original description", "Updated description"))
        self.changelog.write_text(self.changelog.read_text().replace("1.2.3-1", "2:4.0+fips-2"))
        _, packages, version = source_definition(self.control, self.changelog)
        self.assertEqual(version, "2:4.0+fips-2")
        self.assertEqual(packages["libexample"]["Description"], "Updated description")

    def test_finalized_control_reuses_its_existing_version(self):
        """Existing binary-control owners do not need a fabricated source changelog."""
        self.control.write_text(
            "Package: libexample\nVersion: 2.0\nArchitecture: amd64\n"
            "Maintainer: Example <example@example.invalid>\nDescription: Binary control\n")
        source, packages, version = source_definition(self.control)
        self.assertEqual(source["Source"], "libexample")
        self.assertEqual(version, "2.0")
        self.assertNotIn("Version", packages["libexample"])
        with self.assertRaisesRegex(ValueError, "finalized control"):
            source_definition(self.control, self.changelog)

    def test_source_control_cannot_borrow_another_sources_version(self):
        """A wrong changelog must fail instead of producing convincing wrong metadata."""
        self.changelog.write_text(self.changelog.read_text().replace("example (", "another ("))
        with self.assertRaisesRegex(ValueError, "source names differ"):
            source_definition(self.control, self.changelog)
        with self.assertRaisesRegex(ValueError, "requires debian/changelog"):
            source_definition(self.control)

    def test_undefined_substitutions_are_not_silently_deleted(self):
        """dpkg's warning-and-empty default must not hide missing dependency producers."""
        with self.assertRaisesRegex(ValueError, "python3:Depends"):
            check_substitutions({"Depends": "${python3:Depends}"}, {})
        with self.assertRaisesRegex(ValueError, "missing:Depends"):
            check_substitutions({"Depends": "${custom:Depends}"}, {"custom:Depends": "${missing:Depends}"})
        check_substitutions({"Depends": "libexample (= ${binary:Version}), ${shlibs:Depends}"},
                            {"shlibs:Depends": "libc6 (>= 2.38)"})

    def test_optional_substvars_keep_their_produced_values(self):
        """Read standard optional/required syntax without replacing real helper results."""
        path = self.root / "substvars"
        path.write_text("# generated by Debian helpers\nmisc:Depends?=debconf (>= 0.5)\npython3:Depends!=python3:any\n")
        self.assertEqual(read_substvars(path), {"misc:Depends": "debconf (>= 0.5)", "python3:Depends": "python3:any"})
        path.write_text("misc:Depends=one\nmisc:Depends=two\n")
        with self.assertRaisesRegex(ValueError, "duplicate"):
            read_substvars(path)

    def test_target_metadata_does_not_search_execution_libraries_or_host_database(self):
        """Even a native build must resolve only the explicitly declared target libraries."""
        tools = self.root / "exec-tools"
        scratch = self.root / "scratch"
        scratch.mkdir()
        with patch.dict("os.environ", {"LD_LIBRARY_PATH": "/host/lib", "DPKG_ADMINDIR": "/host/dpkg", "PATH": "/host/bin"}):
            environment = tool_environment(tools, scratch, "arm64")
        self.assertEqual(environment["DEB_HOST_ARCH"], "arm64")
        self.assertEqual(environment["PATH"], str(tools / "bin"))
        self.assertEqual(environment["DPKG_ADMINDIR"], str(scratch / "dpkg"))
        self.assertEqual(environment["SONIC_DPKG_SHLIBS_ROOT"], str(scratch / "empty-target-root"))
        self.assertNotIn("LD_LIBRARY_PATH", environment)
        self.assertEqual((scratch / "dpkg/status").read_text(), "")

    def test_dpkg_warning_for_an_undefined_variable_is_a_build_failure(self):
        """A successful process status alone does not prove complete dependency metadata."""
        scratch = self.root / "scratch"
        scratch.mkdir()
        tool = DebianTools(self.root / "exec-tools", scratch, "amd64")
        with patch("runtime_packages.subprocess.run") as run:
            run.return_value.returncode = 0
            run.return_value.stdout = ""
            run.return_value.stderr = "dpkg-gencontrol: warning: substitution variable ${unknown:Depends} used, but is not defined\n"
            with self.assertRaisesRegex(ValueError, "unknown:Depends"):
                tool.run("dpkg-gencontrol")

    def test_wrong_target_elf_is_rejected_without_executing_it(self):
        """A cross build cannot describe an execution-architecture ELF as its target output."""
        payload = self.root / "payload"
        payload.mkdir()
        header = bytearray(64)
        header[:6] = b"\x7fELF\x02\x01"
        struct.pack_into("<HH", header, 16, 3, 183)
        library = payload / "libexample.so"
        library.write_bytes(header)
        self.assertEqual(elf_files(payload, "arm64"), [library])
        with self.assertRaisesRegex(ValueError, "target architecture"):
            elf_files(payload, "amd64")

    def test_source_dependency_wins_over_old_apt_package_but_conflicts_fail(self):
        """The source-built replacement supplies symbols; incompatible source copies fail."""
        apt = {"name": "libexample", "kind": "apt", "payload_sha256": "old",
               "fields": {"Package": "libexample", "Version": "1.0", "Architecture": "amd64"}}
        source = {**apt, "kind": "source", "payload_sha256": "new",
                  "fields": {**apt["fields"], "Version": "2.0"}}
        for entries in ([apt, source], [source, apt]):
            self.assertEqual(unique_dependencies(entries, "amd64")["libexample"], source)
        with self.assertRaisesRegex(ValueError, "conflicting"):
            unique_dependencies([source, {**source, "payload_sha256": "other"}], "amd64")
        with self.assertRaisesRegex(ValueError, "target architecture"):
            unique_dependencies([source], "arm64")

    def test_changed_dependency_control_fails_its_manifest_hash(self):
        """A dependency's generated package facts must remain bound to its recorded inputs."""
        tree = self.root / "dependency"
        control = tree / "packages/libexample/DEBIAN/control"
        control.parent.mkdir(parents=True)
        control.write_text("Package: libexample\nVersion: 2.0\nArchitecture: amd64\n")
        manifest = {"schema": 1, "architecture": "amd64", "packages": [{
            "root": "packages/libexample", "kind": "source", "payload_sha256": "a" * 64,
            "control_sha256": sha(control)}]}
        (tree / "manifest.json").write_text(json.dumps(manifest))
        self.assertEqual(dependency_records([tree], "amd64")[0]["name"], "libexample")
        control.write_text(control.read_text().replace("2.0", "3.0"))
        with self.assertRaisesRegex(ValueError, "changed after generation"):
            dependency_records([tree], "amd64")

    def test_tar_path_cannot_escape_before_standard_extraction(self):
        """Reject unsafe archive members before invoking the declared extraction tool."""
        path = self.root / "unsafe.tar"
        with tarfile.open(path, "w") as archive:
            entry = tarfile.TarInfo("../outside")
            entry.size = 1
            archive.addfile(entry, io.BytesIO(b"x"))
        with self.assertRaisesRegex(ValueError, "unsafe runtime TAR path"):
            validate_archive(path)

    def test_common_required_paths_follow_the_selected_architecture(self):
        """A producer checks Common's SONAME and DB configuration before publishing."""
        required = ["usr/lib/{multiarch}/libswsscommon.so.0",
                    "var/run/redis/sonic-db/database_config.json"]
        for architecture, multiarch in (("amd64", "x86_64-linux-gnu"), ("arm64", "aarch64-linux-gnu")):
            with self.subTest(architecture=architecture):
                payload = self.root / (architecture + ".tar")
                with tarfile.open(payload, "w") as archive:
                    for path in required:
                        item = tarfile.TarInfo(path.format(multiarch=multiarch))
                        archive.addfile(item, io.BytesIO())
                validate_required_paths(payload, required, architecture, "libswsscommon")
                with self.assertRaisesRegex(ValueError, "libswsscommon.so.0"):
                    validate_required_paths(payload, required, "arm64" if architecture == "amd64" else "amd64", "libswsscommon")

    def test_common_missing_soname_is_rejected_even_when_the_tar_exists(self):
        """Valid TAR bytes alone do not establish the required runtime layout."""
        payload = self.root / "common.tar"
        with tarfile.open(payload, "w") as archive:
            archive.addfile(tarfile.TarInfo("usr/lib/x86_64-linux-gnu/libswsscommon.so"), io.BytesIO())
        with self.assertRaisesRegex(ValueError, "runtime package lacks required paths: libswsscommon"):
            validate_required_paths(payload, ["usr/lib/{multiarch}/libswsscommon.so.0"], "amd64", "libswsscommon")

    def test_required_paths_reject_empty_unsafe_or_unrecognized_placeholders(self):
        payload = self.root / "empty.tar"
        with tarfile.open(payload, "w"):
            pass
        for paths in ([], ["../escape"], ["/usr/bin/program"], ["usr/{unknown}/program"],
                      ["usr/{multiarch.__class__}/program"], [""], ["."], "usr/bin/program"):
            with self.subTest(paths=paths), self.assertRaises(ValueError):
                validate_required_paths(payload, paths, "amd64", "example")

    def test_group_rejects_wrong_owner_or_duplicate_package(self):
        """Multiple Debian source trees may share one module without losing package ownership."""
        paths = [self.root / "one.json", self.root / "two.json"]
        first = {"schema": 1, "module": "example", "architecture": "amd64",
                 "packages": {"libone": {"runtime_target": "//:one", "required_paths": ["usr/lib/libone.so"]}}}
        second = {**first, "packages": {"libtwo": {"runtime_target": "//:two"}}}
        paths[0].write_text(json.dumps(first))
        paths[1].write_text(json.dumps(second))
        output = self.root / "combined.json"
        merge(paths, output)
        self.assertEqual(set(json.loads(output.read_text())["packages"]), {"libone", "libtwo"})
        self.assertEqual(json.loads(output.read_text())["packages"]["libone"]["required_paths"], ["usr/lib/libone.so"])
        paths[1].write_text(json.dumps(first))
        with self.assertRaisesRegex(ValueError, "duplicate"):
            merge(paths, output)
        paths[1].write_text(json.dumps({**second, "module": "another"}))
        with self.assertRaisesRegex(ValueError, "different owner"):
            merge(paths, output)


if __name__ == "__main__":
    unittest.main()
