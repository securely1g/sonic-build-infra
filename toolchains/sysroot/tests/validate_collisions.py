#!/usr/bin/env python3
"""Query test repositories to check overlapping sysroot package files safely."""

import argparse
import io
import json
from pathlib import Path
import platform
import shutil
import subprocess
import tarfile


def entries():
    # Include bytes that are not UTF-8: an accidental lossy text comparison must
    # neither reject identical binary files nor accept different binary files.
    return {
        "usr": ("directory", b"", 0o755),
        "usr/include": ("directory", b"", 0o755),
        "usr/lib": ("directory", b"", 0o755),
        "usr/include/fixture.h": ("file", b"same header\n", 0o644),
        "usr/include/binary.h": ("file", b"\x00\x80\xff\n", 0o644),
        "usr/lib/libfixture.so.1": ("file", b"first library\n", 0o644),
        "usr/lib/libfixture.so.2": ("file", b"second library\n", 0o644),
        "usr/lib/libfixture.so": ("symlink", "libfixture.so.1", 0o777),
    }


def write_archive(path, contents, timestamp):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tarfile.open(path, "w:xz", format=tarfile.USTAR_FORMAT) as archive:
        for name, (kind, value, mode) in contents.items():
            member = tarfile.TarInfo("./" + name)
            member.uid = member.gid = 0
            member.mtime = timestamp
            member.mode = mode
            stream = None
            if kind == "directory":
                member.type = tarfile.DIRTYPE
            elif kind == "symlink":
                member.type = tarfile.SYMTYPE
                member.linkname = value
            else:
                member.size = len(value)
                stream = io.BytesIO(value)
            archive.addfile(member, stream)


def cases():
    # Different timestamps are permitted: Debian builds the two architectures
    # independently. Contents, permissions and link targets must still match.
    yield "identical", entries(), entries(), None
    for name, path, replacement, failure in (
        ("different_text", "usr/include/fixture.h", ("file", b"changed header\n", 0o644), "content"),
        ("different_binary", "usr/include/binary.h", ("file", b"\x00\x81\xff\n", 0o644), "content"),
        ("different_mode", "usr/include/fixture.h", ("file", b"same header\n", 0o600), "metadata"),
        ("different_link", "usr/lib/libfixture.so", ("symlink", "libfixture.so.2", 0o777), "metadata"),
        ("different_type", "usr/include/fixture.h", ("directory", b"", 0o644), "metadata"),
    ):
        changed = entries()
        changed[path] = replacement
        yield name, entries(), changed, f"Sysroot {failure} conflict at {path}"
    for kind, value, mode in (("symlink", "../lib", 0o777), ("file", b"not a directory", 0o644)):
        first, second = entries(), entries()
        first["usr/include/parent"] = (kind, value, mode)
        # Do not add a directory entry for parent. The guard must detect the
        # parent-child conflict across packages even without that entry.
        second["usr/include/parent/child.h"] = ("file", b"child\n", 0o644)
        yield f"{kind}_parent", first, second, (
            "Sysroot path usr/include/parent/child.h has non-directory parent usr/include/parent"
        )
    for name, target, failure in (
        ("escaping_link", "../../../outside", "Sysroot symlink escapes the root:"),
        ("absolute_link", "/outside", "Non-relative sysroot symlink:"),
    ):
        changed = entries()
        changed["usr/include/escape"] = ("symlink", target, 0o777)
        yield name, entries(), changed, failure


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bazel", default="bazel")
    parser.add_argument("--startup-option", action="append", default=[])
    parser.add_argument("--bazel-option", action="append", default=[])
    parser.add_argument("--artifacts", required=True, type=Path)
    args = parser.parse_args()
    artifacts = args.artifacts.resolve()
    consumer = artifacts / "consumer"
    consumer.mkdir(parents=True, exist_ok=True)
    source_root = Path(__file__).resolve().parents[3]
    architecture = {"x86_64": "amd64", "aarch64": "arm64"}[platform.machine()]
    notice = "# AUTO-GENERATED by validate_collisions.py. DO NOT EDIT MANUALLY.\n"
    (consumer / ".bazelrc").write_text(notice + (Path(__file__).parent / "consumer/.bazelrc").read_text())
    (consumer / "BUILD.bazel").write_text(notice + 'exports_files(glob(["fixtures/**/*.tar.xz"]))\n')
    module = notice + f'''module(name = "sysroot_collision_tests")
bazel_dep(name = "sonic-build-infra", version = "0.0.16", repo_name = "sonic_build_infra")
local_path_override(module_name = "sonic-build-infra", path = {json.dumps(str(source_root))})
bazel_dep(name = "tar.bzl", version = "0.10.5-sonic.1")
single_version_override(module_name = "tar.bzl", version = "0.10.5-sonic.1")
tar = use_extension("@tar.bzl//tar:extensions.bzl", "toolchains")
use_repo(tar, "bsd_tar_toolchains_linux_{architecture}")
fixture = use_repo_rule("@sonic_build_infra//toolchains/sysroot/tests:collision_fixture.bzl", "collision_fixture")
'''
    expected = {
        "paths": 8, "shared_paths": 8, "shared_files": 4,
        "shared_symlinks": 1, "shared_directories": 3,
        "file_comparisons": 4, "comparison": "exact bytes",
    }
    fixtures = list(cases())
    for name, first, second, failure in fixtures:
        for part, contents, timestamp in (("first", first, 1), ("second", second, 2)):
            write_archive(consumer / f"fixtures/{name}/{part}/data.tar.xz", contents, timestamp)
        module += f'''fixture(
    name = "{name}",
    archives = ["//:fixtures/{name}/first/data.tar.xz", "//:fixtures/{name}/second/data.tar.xz"],
    tar = "@bsd_tar_toolchains_linux_{architecture}//:tar",
    expected = {json.dumps(json.dumps(expected) if failure is None else "")},
)
'''
    (consumer / "MODULE.bazel").write_text(module)
    receipt = {
        "_generated": {"notice": "AUTO-GENERATED. DO NOT EDIT MANUALLY.", "generator": "toolchains/sysroot/tests/validate_collisions.py"},
        "architecture": architecture,
        "cases": {},
    }
    for name, _, _, failure in fixtures:
        # Query fetches repositories and exercises extraction; it runs no build
        # actions and cannot create Debian packages or compiler outputs.
        command = [args.bazel, *args.startup_option, "query", *args.bazel_option,
                   f"@{name}//:collision_check.json"]
        result = subprocess.run(command, cwd=consumer, text=True, capture_output=True, check=False)
        log = result.stdout + result.stderr
        (artifacts / f"{name}.log").write_text(log)
        if failure is None:
            assert result.returncode == 0, f"Identical package contents were rejected:\n{log}"
        else:
            assert result.returncode != 0 and failure in log, f"Expected {failure!r}:\n{log}"
        receipt["cases"][name] = {
            "command": command,
            "returncode": result.returncode,
            "expected_failure": failure,
        }
        (artifacts / "validation.json").write_text(json.dumps(receipt, indent=2) + "\n")
        print(f"Validated sysroot archive case: {name}", flush=True)
    lockfile = consumer / "MODULE.bazel.lock"
    assert lockfile.is_file(), "Keep Bazel's generated module lockfile enabled for evidence"
    shutil.copy2(lockfile, artifacts / "MODULE.bazel.lock")
    print(f"All {len(fixtures)} archive collision checks passed on {architecture}")


if __name__ == "__main__":
    main()
