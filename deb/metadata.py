"""Connect declared package inputs to Debian's standard metadata commands.

Archive extraction belongs to the declared BSD tar tool. Dependency and version
semantics belong to dpkg-shlibdeps, dpkg-gensymbols and dpkg-gencontrol.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

NOTICE = "AUTO-GENERATED by deb/metadata.py. DO NOT EDIT MANUALLY."


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def elf_files(root):
    result = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink() or not path.is_file() or "usr/lib/debug" in path.relative_to(root).as_posix():
            continue
        with path.open("rb") as source:
            header = source.read(18)
        if len(header) == 18 and header[:4] == b"\x7fELF":
            order = "little" if header[5] == 1 else "big"
            if int.from_bytes(header[16:18], order) in (2, 3):
                result.append(path)
    return result


def library_directories(root):
    return sorted({path.parent for path in root.rglob("*.so*") if not path.is_symlink() and path.is_file()})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("manifest", "tar", "gencontrol", "shlibdeps", "gensymbols"):
        parser.add_argument("--" + name, type=Path, required=True)
    args = parser.parse_args()
    execroot = Path.cwd()
    config = json.loads(args.manifest.read_text())
    tools = {name: str(getattr(args, name).absolute()) for name in ("tar", "gencontrol", "shlibdeps", "gensymbols")}
    outputs = {name: execroot / value for name, value in config["outputs"].items()}
    environment = dict(os.environ, DEB_HOST_ARCH=config["architecture"], LANG="C", LC_ALL="C")
    receipt = {"_generated": NOTICE, "package": config["package"], "architecture": config["architecture"], "inputs": {}}

    def source(value):
        path = execroot / value
        receipt["inputs"][value] = sha(path)
        return path

    def run(command, cwd):
        completed = subprocess.run(command, cwd=cwd, env=environment, text=True, capture_output=True)
        if completed.stderr:
            print(completed.stderr, end="", flush=True)
        if completed.returncode or "unknown substitution variable" in completed.stderr:
            raise RuntimeError("Debian metadata command failed: " + repr(command) + "\n" + completed.stdout + completed.stderr)
        return completed

    with tempfile.TemporaryDirectory(prefix="sonic-debian-metadata-") as temporary:
        work = Path(temporary)
        debian = work / "debian"
        package = work / "package"
        (package / "DEBIAN").mkdir(parents=True)
        debian.mkdir()
        shutil.copyfile(source(config["control"]), debian / "control")
        shutil.copyfile(source(config["changelog"]), debian / "changelog")
        run([tools["tar"], "-xf", str(source(config["data"])), "-C", str(package)], work)
        roots = [package]
        for index, row in enumerate(config["dependencies"]):
            root = work / ("dependency-" + str(index))
            (root / "DEBIAN").mkdir(parents=True)
            run([tools["tar"], "-xf", str(source(row["data"])), "-C", str(root)], work)
            if row.get("control_tar"):
                run([tools["tar"], "-xf", str(source(row["control_tar"])), "-C", str(root / "DEBIAN")], work)
            for name in ("symbols", "shlibs"):
                if row.get(name):
                    shutil.copyfile(source(row[name]), root / "DEBIAN" / name)
            roots.append(root)
        binaries = elf_files(package)
        receipt["elf_files"] = [str(path.relative_to(package)) for path in binaries]
        version = ["-v" + config["version"]] if config.get("version") else []
        if "symbols" in outputs:
            command = [tools["gensymbols"], "-a" + config["architecture"], "-p" + config["package"], "-P" + str(package), *version]
            if config.get("symbols"):
                command.append("-I" + str(source(config["symbols"])))
            command += ["-e" + str(path) for path in binaries if ".so" in path.name]
            run([*command, "-O" + str(package / "DEBIAN/symbols")], work)
            shutil.copyfile(package / "DEBIAN/symbols", outputs["symbols"])
        variables = work / "substvars"
        text = source(config["substvars"]).read_text() if config.get("substvars") else ""
        names = {line.split("=", 1)[0] for line in text.splitlines() if "=" in line and not line.startswith("#")}
        for name, value in sorted(config["substitutions"].items()):
            if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9:._-]*", name) or "\n" in value or name in names:
                raise ValueError("Invalid or duplicate substitution: " + name)
            text += "\n" + name + "=" + value
        variables.write_text("# " + NOTICE + "\n" + text + "\n")
        if binaries:
            command = [tools["shlibdeps"], "-T" + str(variables), "-x" + config["package"]]
            for root in roots:
                command.extend("-l" + str(path) for path in library_directories(root))
                command.append("-S" + str(root))
            run(command + [str(path) for path in binaries], work)
        else:
            with variables.open("a") as destination:
                destination.write("shlibs:Depends=\n")
        run([tools["gencontrol"], "-p" + config["package"], "-P" + str(package), "-T" + str(variables), *version, "-O" + str(outputs["control"])], work)
        shutil.copyfile(variables, outputs["substvars"])
        receipt["outputs"] = {name: sha(path) for name, path in outputs.items() if name != "receipt"}
        receipt["status"] = "passed"
        outputs["receipt"].write_text(json.dumps(receipt, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
